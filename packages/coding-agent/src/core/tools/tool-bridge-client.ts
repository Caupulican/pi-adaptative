import type { TSchema } from "typebox";
import {
	TOOL_BRIDGE_ADDRESS_ENV,
	TOOL_BRIDGE_CLIENT_MODULE,
	TOOL_BRIDGE_TOKEN_ENV,
	type ToolBridgeToolName,
} from "./tool-bridge-policy.ts";

/**
 * The `pi_tools` module a bridged script imports, generated per run for the tools that run named. Each function
 * sends one call over the run's channel and returns the tool's text, or raises a `ToolError` subclass the script can
 * catch: `ToolRefused` (a gate or the session refused it), `ToolFailed` (the tool ran and failed), `ToolLimit` (the
 * run's call limit), `ToolCancelled` (the run is ending). Calls from several threads take turns on one connection.
 */

export interface ToolBridgeClientTool {
	readonly name: ToolBridgeToolName;
	/** The tool's parameter schema, when the session offers the tool; it gives the function its signature. */
	readonly parameters?: TSchema;
}

const PYTHON_IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/;
const PYTHON_RESERVED: ReadonlySet<string> = new Set([
	"False",
	"None",
	"True",
	"and",
	"as",
	"assert",
	"async",
	"await",
	"break",
	"class",
	"continue",
	"def",
	"del",
	"elif",
	"else",
	"except",
	"finally",
	"for",
	"from",
	"global",
	"if",
	"import",
	"in",
	"is",
	"lambda",
	"nonlocal",
	"not",
	"or",
	"pass",
	"raise",
	"return",
	"try",
	"while",
	"with",
	"yield",
]);

function schemaFields(parameters: TSchema | undefined): { required: string[]; optional: string[] } | undefined {
	const properties = (parameters as { properties?: Record<string, unknown> } | undefined)?.properties;
	if (!properties) return undefined;
	const names = Object.keys(properties);
	if (names.some((name) => !PYTHON_IDENTIFIER.test(name) || PYTHON_RESERVED.has(name) || name.startsWith("_")))
		return undefined;
	const requiredList = (parameters as { required?: unknown }).required;
	const required = new Set(Array.isArray(requiredList) ? requiredList.filter((n) => typeof n === "string") : []);
	return {
		required: names.filter((name) => required.has(name)),
		optional: names.filter((name) => !required.has(name)),
	};
}

/**
 * Required fields may be passed by position, optional ones by keyword (None leaves one unset); a schema Python cannot
 * name takes `**args`.
 */
function renderFunction(tool: ToolBridgeClientTool): string {
	const fields = schemaFields(tool.parameters);
	if (!fields) {
		return `def ${tool.name}(**args):\n    """Pi \`${tool.name}\` tool; returns its text output."""\n    return _call(${JSON.stringify(tool.name)}, args)\n`;
	}
	const signature = [
		...fields.required,
		...(fields.optional.length > 0 ? ["*", ...fields.optional.map((name) => `${name}=None`)] : []),
	].join(", ");
	const collected = [...fields.required, ...fields.optional].map((name) => `${JSON.stringify(name)}: ${name}`);
	return `def ${tool.name}(${signature}):\n    """Pi \`${tool.name}\` tool; returns its text output."""\n    return _call(${JSON.stringify(tool.name)}, _given({${collected.join(", ")}}))\n`;
}

export function renderToolBridgeClient(tools: readonly ToolBridgeClientTool[]): string {
	const names = tools.map((tool) => tool.name);
	return `"""Pi tools for this script run (generated by the python tool; valid only while this run lasts).

Each function calls the Pi tool of the same name. The call is admitted exactly like a direct call of that tool and
returns the tool's text output. It raises ToolRefused, ToolFailed, ToolLimit or ToolCancelled (all ToolError) when the
call is refused, fails, exceeds this run's call limit, or the run is ending. Only what the script prints reaches the
model.
"""

import io as _io
import json as _json
import os as _os
import socket as _socket
import threading as _threading

__all__ = ${JSON.stringify([...names, "ToolError", "ToolRefused", "ToolFailed", "ToolLimit", "ToolCancelled"])}


class ToolError(Exception):
    def __init__(self, tool, kind, message):
        super().__init__(f"{tool}: {message}")
        self.tool = tool
        self.kind = kind
        self.message = message


class ToolRefused(ToolError):
    pass


class ToolFailed(ToolError):
    pass


class ToolLimit(ToolError):
    pass


class ToolCancelled(ToolError):
    pass


_KINDS = {"refused": ToolRefused, "error": ToolFailed, "limit": ToolLimit, "cancelled": ToolCancelled}
_lock = _threading.Lock()
_channel = None
_next_id = 0


def _given(fields):
    return {name: value for name, value in fields.items() if value is not None}


class _Channel:
    def __init__(self, address, token):
        if address.startswith("\\\\\\\\.\\\\pipe\\\\"):
            raw = open(address, "r+b", buffering=0)
            self._reader = _io.BufferedReader(raw)
            self._write = raw.write
        else:
            sock = _socket.socket(_socket.AF_UNIX, _socket.SOCK_STREAM)
            sock.connect(address)
            self._reader = sock.makefile("rb")
            self._write = sock.sendall
        self.send({"t": "hello", "token": token})
        if self.receive().get("t") != "ready":
            raise ToolRefused("${TOOL_BRIDGE_CLIENT_MODULE}", "refused", "the host refused this connection")

    def send(self, frame):
        view = memoryview((_json.dumps(frame, ensure_ascii=False, separators=(",", ":")) + "\\n").encode("utf-8"))
        while view:
            written = self._write(view)
            if written is None:
                return
            view = view[written:]

    def receive(self):
        line = self._reader.readline()
        if not line:
            raise ToolCancelled("${TOOL_BRIDGE_CLIENT_MODULE}", "cancelled", "the host closed the tool channel")
        return _json.loads(line.decode("utf-8"))


def _call(tool, args):
    global _channel, _next_id
    with _lock:
        if _channel is None:
            address = _os.environ.get("${TOOL_BRIDGE_ADDRESS_ENV}")
            token = _os.environ.get("${TOOL_BRIDGE_TOKEN_ENV}")
            if not address or not token:
                raise ToolRefused(tool, "refused", "no Pi tool channel in this process; run it through the python tool with tools")
            _channel = _Channel(address, token)
        _next_id += 1
        _channel.send({"t": "call", "id": _next_id, "tool": tool, "args": args})
        reply = _channel.receive()
    if reply.get("ok"):
        return reply.get("text", "")
    kind = reply.get("kind", "error")
    raise _KINDS.get(kind, ToolFailed)(tool, kind, reply.get("message", ""))


${tools.map(renderFunction).join("\n\n")}`;
}
