#!/usr/bin/env node
/**
 * Machine charts (D4): one Mermaid state diagram per declared state machine, written to docs/machines/<name>.md from the
 * declared tables themselves. Three charts come from the adopting leaf tables. The fourth is the remote-job delivery
 * model's placer projection, read off the model explored at its full bounds: `projectMachine` refuses a partial search,
 * so the reduced budgets of `check-machine-models.mjs --static` cannot serve here.
 *
 *   node scripts/machine-charts.mjs           writes every chart, and removes a chart whose machine is no longer declared
 *   node scripts/machine-charts.mjs --check   fails when a chart is missing, differs from its table, or has no declared machine
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { WORKER_OUTCOME_MACHINE } from "../packages/coding-agent/src/core/delegation/worker-outcome-machine.ts";
import { FLEET_STOP_MACHINE } from "../packages/coding-agent/src/core/fleet/fleet-admission-machine.ts";
import { PLAN_NODE_MACHINE } from "../packages/coding-agent/src/core/plan/plan-node-machine.ts";
import { remoteJobDeliveryModel } from "../packages/coding-agent/src/core/remote/remote-job-delivery-model.ts";
import { exploreGraph } from "../packages/coding-agent/src/kernel/machine-model-explore.ts";
import { projectMachine } from "../packages/coding-agent/src/kernel/machine-model.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const outputDir = join(root, "docs/machines");

/** Every chart, with the file its table is declared in. */
const CHARTS = [
	{ machine: WORKER_OUTCOME_MACHINE, source: "packages/coding-agent/src/core/delegation/worker-outcome-machine.ts" },
	{ machine: PLAN_NODE_MACHINE, source: "packages/coding-agent/src/core/plan/plan-node-machine.ts" },
	{ machine: FLEET_STOP_MACHINE, source: "packages/coding-agent/src/core/fleet/fleet-admission-machine.ts" },
	{
		machine: projectMachine(remoteJobDeliveryModel, exploreGraph(remoteJobDeliveryModel)),
		source: "packages/coding-agent/src/core/remote/remote-job-delivery-model.ts (placer projection)",
	},
];

/**
 * The Mermaid state diagram of one machine: the initial marker, then one line per declared transition in table order. A
 * state with no transition in or out is drawn alone, so no declared state is left off the chart.
 */
function renderChart(machine) {
	const lines = ["stateDiagram-v2", `[*] --> ${machine.initial}`];
	const drawn = new Set([machine.initial]);
	for (const from of machine.states) {
		for (const [event, to] of Object.entries(machine.transitions[from] ?? {})) {
			lines.push(`${from} --> ${to} : ${event}`);
			drawn.add(from);
			drawn.add(to);
		}
	}
	for (const state of machine.states) if (!drawn.has(state)) lines.push(state);
	return lines.join("\n");
}

function renderDocument(machine, source) {
	return [
		`<!-- Generated by scripts/machine-charts.mjs from ${source}. Edit the declared table, then run node scripts/machine-charts.mjs. -->`,
		"",
		`# ${machine.name}`,
		"",
		"```mermaid",
		renderChart(machine),
		"```",
		"",
	].join("\n");
}

/** The chart files on disk. */
function listedCharts() {
	return existsSync(outputDir) ? readdirSync(outputDir).filter((file) => file.endsWith(".md")) : [];
}

const expected = new Map(CHARTS.map(({ machine, source }) => [`${machine.name}.md`, renderDocument(machine, source)]));

if (process.argv.includes("--check")) {
	const problems = [];
	for (const [file, text] of expected) {
		const path = join(outputDir, file);
		if (!existsSync(path)) problems.push(`docs/machines/${file} is missing`);
		else if (readFileSync(path, "utf8") !== text) problems.push(`docs/machines/${file} differs from its declared table`);
	}
	for (const file of listedCharts()) {
		if (!expected.has(file)) problems.push(`docs/machines/${file} is stale: no declared machine has that name`);
	}
	if (problems.length > 0) {
		for (const problem of problems) console.error(`machine-charts: ${problem}`);
		console.error("machine-charts: run node scripts/machine-charts.mjs to regenerate the charts");
		process.exit(1);
	}
	console.log(`machine charts: ${expected.size} chart(s) match their declared tables`);
} else {
	mkdirSync(outputDir, { recursive: true });
	for (const file of listedCharts()) {
		if (!expected.has(file)) rmSync(join(outputDir, file));
	}
	for (const [file, text] of expected) writeFileSync(join(outputDir, file), text);
	console.log(`machine charts: wrote ${expected.size} chart(s) to docs/machines`);
}
